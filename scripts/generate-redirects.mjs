// Writes public/_redirects from url-map.csv and the owner's list in src/data/redirects.json.
// A no-slash URL and its slash version share one rule, because Netlify matches both forms.
// Validation of the result is in scripts/check-build.mjs. Usage: node scripts/generate-redirects.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const O = 'https://websitemaintenanceservices.org';
const cells = (line) => {
  const o = [];
  let c = '';
  let q = false;
  for (const ch of line) {
    if (ch === '"') q = !q;
    else if (ch === ',' && !q) {
      o.push(c);
      c = '';
    } else c += ch;
  }
  o.push(c);
  return o;
};
const map = readFileSync('url-map.csv', 'utf8').replace(/^﻿/, '').split(/\r?\n/).slice(1).filter(Boolean).map(cells);
const owner = JSON.parse(readFileSync('src/data/redirects.json', 'utf8'));
const base = (p) => (p.length > 1 ? p.replace(/\/$/, '') : p);

const rules = new Map();
const queryRules = [];
const skipped = { slashOnly: 0, queryVariant: 0 };
for (const r of map) {
  if (r[2] !== '301') {
    if (r[3] === 'query-variant') skipped.queryVariant++;
    continue;
  }
  const u = new URL(r[0]);
  const to = r[1].replace(O, '');
  if (u.search) {
    const p = /^\?(p|attachment_id|page_id)=(\d+)$/.exec(u.search);
    if (p) queryRules.push(`${u.pathname}  ${p[1]}=${p[2]}  ${to}  301`);
    else skipped.queryVariant++;
    continue;
  }
  const from = u.pathname;
  if (base(from) === base(to)) {
    skipped.slashOnly++;
    continue;
  }
  const key = base(from);
  if (rules.has(key) && rules.get(key).to !== to) throw new Error(`Conflicting targets for ${key}: ${rules.get(key).to} and ${to}`);
  rules.set(key, { from: key.endsWith('/') || key === '/' ? key : `${key}/`, to });
}

for (const o of owner) {
  if (o.type !== 301 && o.type !== 302) throw new Error(`Redirect ${o.from}: type must be 301 or 302`);
  rules.set(base(o.from), { from: o.from, to: o.to, status: o.type });
}

const lines = ['# Generated by scripts/generate-redirects.mjs from url-map.csv and src/data/redirects.json. Do not edit.', '/feed/  /feed.xml  200'];
lines.push(...queryRules);
for (const r of rules.values()) lines.push(`${r.from}  ${r.to}  ${r.status ?? 301}`);
writeFileSync('public/_redirects', lines.join('\n') + '\n');
console.log(`redirects: ${rules.size} path rules, ${queryRules.length} query rules, 1 feed rewrite; left to Netlify's slash handling: ${skipped.slashOnly}; query variants with no rule: ${skipped.queryVariant}`);
